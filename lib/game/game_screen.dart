class MapTile extends StatelessWidget {
  final int tileType;
  static const double tileSize =
      20.0; // Reduced tile size to fit the larger map

  const MapTile({Key? key, required this.tileType}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    String imagePath;

    switch (tileType) {
      case 0: // Empty/floor
        imagePath = 'assets/images/tile1.png';
        break;
      case 1: // Wall
        imagePath = 'assets/images/wall.png';
        break;
      case 2: // Brick wall
        imagePath = 'assets/images/brick_wall.png';
        break;
      default:
        imagePath = 'assets/images/tile2.png'; // Fallback
    }

    return SizedBox(
      width: tileSize,
      height: tileSize,
      child: Image.asset(
        imagePath,
        width: tileSize,
        height: tileSize,
        fit: BoxFit.cover,
      ),
    );
  }
}
