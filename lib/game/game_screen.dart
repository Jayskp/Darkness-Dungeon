  final Random _random = Random();
  final double tileSize = 16.0; // Adjust as needed for your tile size

  // Asset paths (ensure these are in your pubspec.yaml and project structure, e.g., assets/images/tile_name.png)
  final String brickWallAsset =
      'assets/images/brick_wall.png'; // For tile type 2 in mapLayout
  final String decorativeWallAsset =
      'assets/images/wall.png'; // For tile type 1 in mapLayout
  final String floorTile1Asset =
      'assets/images/tile1.png'; // For tile type 0 in mapLayout
  final String floorTile2Asset =
      'assets/images/tile2.png'; // For tile type 0 in mapLayout

  // This list will store the pre-selected floor tile for each floor cell to ensure consistency
  late List<List<String>> _resolvedFloorTiles;

  @override
  void initState() {
    super.initState();
    _resolveFloorTiles();
  }

  void _resolveFloorTiles() {
    if (mapLayout.isEmpty) return; // Guard against empty mapLayout
    _resolvedFloorTiles = List.generate(mapLayout.length, (i) {
      if (mapLayout[i].isEmpty)
        return List<String>.empty(); // Guard against empty rows
      return List.generate(mapLayout[i].length, (j) {
        if (mapLayout[i][j] == 0) {
          return _random.nextBool() ? floorTile1Asset : floorTile2Asset;
        }
        return ''; // Not a floor tile, asset path will be determined in _getTileWidget
      });
    });
  }

  Widget _getTileWidget(int tileType, int rowIndex, int colIndex) {
    String assetPath;
    switch (tileType) {
      case 0: // Floor
        // Ensure rowIndex and colIndex are within bounds for _resolvedFloorTiles
        if (rowIndex < _resolvedFloorTiles.length &&
            colIndex < _resolvedFloorTiles[rowIndex].length) {
          assetPath = _resolvedFloorTiles[rowIndex][colIndex];
        } else {
          // Fallback if something is wrong with mapLayout or _resolvedFloorTiles generation
          assetPath = floorTile1Asset;
        }
        break;
      case 1: // Decorative Wall (uses wall.png)
        assetPath = decorativeWallAsset;
        break;
      case 2: // Main Wall (uses brick_wall.png)
        assetPath = brickWallAsset;
        break;
      default:
        // For any other number, render an empty space (e.g., transparent or matching background)
        // This will effectively be a black square due to the parent container's color.
        return SizedBox(width: tileSize, height: tileSize);
    }
    return Image.asset(
      assetPath,
      width: tileSize,
      height: tileSize,
      fit: BoxFit.cover,
      errorBuilder: (
        BuildContext context,
        Object exception,
        StackTrace? stackTrace,
      ) {
        // Placeholder for missing or error in loading asset
        return Container(
          width: tileSize,
          height: tileSize,
          color: Colors.redAccent,
          child: Center(
            child: Icon(
              Icons.error_outline,
              color: Colors.white,
              size: tileSize * 0.8,
            ),
          ),
        );
      },
    );
  }

  @override
  Widget build(BuildContext context) {
    if (mapLayout.isEmpty) {
      return const Center(
        child: Text(
          "Map layout is empty.",
          style: TextStyle(color: Colors.white),
        ),
      );
    }

    List<Widget> rowWidgets = [];
    for (int i = 0; i < mapLayout.length; i++) {
      List<Widget> colTileWidgets = [];
      if (mapLayout[i].isEmpty) continue; // Skip empty rows
      for (int j = 0; j < mapLayout[i].length; j++) {
        colTileWidgets.add(_getTileWidget(mapLayout[i][j], i, j));
      }
      rowWidgets.add(
        Row(
          mainAxisAlignment: MainAxisAlignment.start,
          children: colTileWidgets,
        ),
      );
    }

    return SingleChildScrollView(
      scrollDirection: Axis.vertical,
      child: SingleChildScrollView(
        scrollDirection: Axis.horizontal,
        child: Container(
          color: Colors.black, // Background for the map area
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: rowWidgets,
          ),
        ),
      ),
    );
  }
